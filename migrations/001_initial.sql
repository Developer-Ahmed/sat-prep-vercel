CREATE TABLE IF NOT EXISTS schema_migrations (
  name text PRIMARY KEY,
  checksum text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_users (
  id text PRIMARY KEY CHECK (btrim(id) <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS questions (
  row_id text PRIMARY KEY CHECK (btrim(row_id) <> ''),
  subject text NOT NULL DEFAULT 'math' CHECK (subject IN ('math', 'english')),
  program text,
  domain text,
  domain_desc text,
  skill text,
  skill_desc text,
  difficulty text,
  excluded_bluebook boolean NOT NULL DEFAULT false,
  raw_json jsonb NOT NULL,
  imported_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS question_source_refs (
  question_row_id text NOT NULL REFERENCES questions(row_id) ON DELETE CASCADE,
  source text NOT NULL CHECK (source IN ('collegeboard')),
  source_question_id text NOT NULL,
  uid text,
  external_id text,
  ibn text,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source, source_question_id),
  UNIQUE (question_row_id, source)
);

CREATE TABLE IF NOT EXISTS question_pool_memberships (
  question_row_id text NOT NULL REFERENCES questions(row_id) ON DELETE CASCADE,
  pool text NOT NULL CHECK (pool IN ('main', 'new')),
  active boolean NOT NULL DEFAULT true,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (question_row_id, pool)
);

CREATE TABLE IF NOT EXISTS app_settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS question_content (
  question_row_id text PRIMARY KEY REFERENCES questions(row_id) ON DELETE CASCADE,
  data_json jsonb NOT NULL,
  fetched_at timestamptz NOT NULL,
  content_version integer NOT NULL DEFAULT 1 CHECK (content_version > 0)
);

CREATE TABLE IF NOT EXISTS progress (
  user_id text NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  row_id text NOT NULL REFERENCES questions(row_id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'unanswered' CHECK (status IN ('unanswered', 'correct', 'incorrect', 'skipped')),
  flagged boolean NOT NULL DEFAULT false,
  selected_answer text,
  answered_at timestamptz,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (user_id, row_id),
  CHECK (
    (status IN ('correct', 'incorrect') AND answered_at IS NOT NULL AND btrim(COALESCE(selected_answer, '')) <> '')
    OR (status IN ('unanswered', 'skipped') AND answered_at IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS vocab_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id text REFERENCES app_users(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('word', 'root')),
  term text NOT NULL CHECK (btrim(term) <> ''),
  definition text NOT NULL CHECK (btrim(definition) <> ''),
  example text NOT NULL DEFAULT '',
  family text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT 'user',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_vocab_items_shared_term
  ON vocab_items (kind, lower(term)) WHERE owner_user_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_vocab_items_user_term
  ON vocab_items (owner_user_id, kind, lower(term)) WHERE owner_user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS vocab_sets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text NOT NULL CHECK (btrim(name) <> ''),
  description text NOT NULL DEFAULT '',
  kind text NOT NULL CHECK (kind IN ('word', 'root')),
  built_in boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS vocab_set_items (
  set_id bigint NOT NULL REFERENCES vocab_sets(id) ON DELETE CASCADE,
  item_id bigint NOT NULL REFERENCES vocab_items(id) ON DELETE CASCADE,
  position integer NOT NULL DEFAULT 0,
  added_at timestamptz NOT NULL,
  display_term text,
  display_definition text,
  display_example text,
  PRIMARY KEY (set_id, item_id)
);

CREATE TABLE IF NOT EXISTS user_vocab_set_items (
  user_id text NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  set_id bigint NOT NULL REFERENCES vocab_sets(id) ON DELETE CASCADE,
  item_id bigint NOT NULL REFERENCES vocab_items(id) ON DELETE CASCADE,
  position integer NOT NULL DEFAULT 0,
  added_at timestamptz NOT NULL,
  display_term text,
  display_definition text,
  display_example text,
  PRIMARY KEY (user_id, set_id, item_id)
);

CREATE TABLE IF NOT EXISTS vocab_progress (
  user_id text NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  set_id bigint NOT NULL REFERENCES vocab_sets(id) ON DELETE CASCADE,
  item_id bigint NOT NULL REFERENCES vocab_items(id) ON DELETE CASCADE,
  state text NOT NULL DEFAULT 'new' CHECK (state IN ('new', 'learning', 'review', 'mastered')),
  due_at timestamptz NOT NULL,
  interval_days integer NOT NULL DEFAULT 0 CHECK (interval_days >= 0),
  streak integer NOT NULL DEFAULT 0 CHECK (streak >= 0),
  lapses integer NOT NULL DEFAULT 0 CHECK (lapses >= 0),
  last_reviewed_at timestamptz,
  PRIMARY KEY (user_id, set_id, item_id)
);

CREATE TABLE IF NOT EXISTS vocab_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  request_id text NOT NULL CHECK (request_id ~ '^[A-Za-z0-9_-]{8,128}$'),
  set_id bigint NOT NULL REFERENCES vocab_sets(id) ON DELETE CASCADE,
  item_id bigint NOT NULL REFERENCES vocab_items(id) ON DELETE CASCADE,
  rating text NOT NULL CHECK (rating IN ('again', 'hard', 'good', 'easy')),
  correct boolean NOT NULL,
  reviewed_at timestamptz NOT NULL,
  CHECK (correct = (rating <> 'again'))
);

CREATE INDEX IF NOT EXISTS idx_questions_subject_available ON questions(subject, excluded_bluebook);
CREATE INDEX IF NOT EXISTS idx_question_pool_memberships_active
  ON question_pool_memberships(pool, question_row_id) WHERE active;
CREATE INDEX IF NOT EXISTS idx_question_source_refs_question ON question_source_refs(question_row_id);
CREATE INDEX IF NOT EXISTS idx_vocab_items_kind ON vocab_items(kind, active);
CREATE INDEX IF NOT EXISTS idx_vocab_set_items_item ON vocab_set_items(item_id);
CREATE INDEX IF NOT EXISTS idx_vocab_progress_due ON vocab_progress(user_id, set_id, due_at);
CREATE INDEX IF NOT EXISTS idx_vocab_reviews_date ON vocab_reviews(user_id, set_id, reviewed_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_vocab_reviews_user_request
  ON vocab_reviews(user_id, request_id);

CREATE VIEW question_catalog AS
SELECT
  q.row_id,
  q.subject,
  pm.pool,
  sr.source,
  sr.source_question_id AS question_id,
  sr.uid,
  sr.external_id,
  sr.ibn,
  q.program,
  q.domain,
  q.domain_desc,
  q.skill,
  q.skill_desc,
  q.difficulty,
  q.excluded_bluebook,
  q.raw_json,
  q.imported_at
FROM questions q
JOIN question_pool_memberships pm ON pm.question_row_id = q.row_id AND pm.active
JOIN question_source_refs sr ON sr.question_row_id = q.row_id;
