CREATE TABLE IF NOT EXISTS test_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  subject text NOT NULL CHECK (subject IN ('math', 'english')),
  pool text NOT NULL CHECK (pool IN ('main', 'new')),
  kind text NOT NULL CHECK (kind IN ('practice', 'review_incorrect', 'review_flagged')),
  created_at timestamptz NOT NULL DEFAULT now(),
  submitted_at timestamptz,
  CHECK (submitted_at IS NULL OR submitted_at >= created_at),
  UNIQUE (user_id, id)
);

CREATE TABLE IF NOT EXISTS test_modules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  session_id bigint NOT NULL,
  position smallint NOT NULL CHECK (position > 0),
  title text NOT NULL CHECK (btrim(title) <> ''),
  duration_seconds integer NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  submitted_at timestamptz,
  CHECK (started_at IS NULL OR started_at >= created_at),
  CHECK (submitted_at IS NULL OR submitted_at >= COALESCE(started_at, created_at)),
  UNIQUE (user_id, id),
  UNIQUE (user_id, session_id, position),
  FOREIGN KEY (user_id, session_id) REFERENCES test_sessions(user_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS module_questions (
  user_id text NOT NULL,
  module_id bigint NOT NULL,
  position smallint NOT NULL CHECK (position > 0),
  row_id text NOT NULL REFERENCES questions(row_id) ON DELETE RESTRICT,
  PRIMARY KEY (user_id, module_id, position),
  UNIQUE (user_id, module_id, row_id),
  FOREIGN KEY (user_id, module_id) REFERENCES test_modules(user_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS module_responses (
  user_id text NOT NULL,
  module_id bigint NOT NULL,
  row_id text NOT NULL,
  answer text NOT NULL DEFAULT '',
  flagged boolean NOT NULL DEFAULT false,
  status text CHECK (status IS NULL OR status IN ('unanswered', 'correct', 'incorrect', 'skipped')),
  is_correct boolean,
  time_spent_seconds integer NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, module_id, row_id),
  CHECK (
    (status IS NULL AND is_correct IS NULL)
    OR (status IN ('unanswered', 'skipped') AND is_correct IS NULL)
    OR (status = 'correct' AND is_correct)
    OR (status = 'incorrect' AND NOT is_correct)
  ),
  FOREIGN KEY (user_id, module_id, row_id)
    REFERENCES module_questions(user_id, module_id, row_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS response_time_segments (
  user_id text NOT NULL,
  module_id bigint NOT NULL,
  row_id text NOT NULL,
  pass_index smallint NOT NULL CHECK (pass_index > 0),
  seconds integer NOT NULL DEFAULT 0 CHECK (seconds >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, module_id, row_id, pass_index),
  FOREIGN KEY (user_id, module_id, row_id)
    REFERENCES module_responses(user_id, module_id, row_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_test_sessions_user_catalog_created
  ON test_sessions (user_id, subject, pool, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_test_modules_session
  ON test_modules (user_id, session_id, position);
